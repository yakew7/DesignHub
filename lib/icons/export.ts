/** "tabler:brand-github" → "BrandGithubIcon" */
export function componentName(id: IconId): string {
  const { name } = splitIconId(id);
  const pascal = name
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
  const safe = /^[0-9]/.test(pascal) ? `Icon${pascal}` : pascal;
  return `${safe}Icon`;
}

/** Converts SVG markup attributes to their JSX spelling (stroke-width → strokeWidth). */
export function svgToJsx(svg: string): string {
  return svg
    .replace(/\s(class)=/g, " className=")
    .replace(
      /\s(xlink):([a-z]+)=/g,
      (_, ns: string, attr: string) => ` ${ns}${attr.charAt(0).toUpperCase()}${attr.slice(1)}=`,
    )
    .replace(/\s([a-z]+(?:-[a-z]+)+)=/g, (match, attr: string) =>
      attr.startsWith("data-") || attr.startsWith("aria-")
        ? match
        : ` ${attr.replace(/-([a-z])/g, (_: string, letter: string) => letter.toUpperCase())}=`,
    );
}

function reactComponent(id: IconId, icon: IconData, style: IconStyle): string {
  const name = componentName(id);
  const svg = buildIconSvg(icon, { ...style, size: 24 }, { uniqueIds: true });
  const inner = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  return `import type { SVGProps } from "react";

// ${id} - generated by DesignHub. Size with font-size or width/height; color inherits currentColor.
export function ${name}(props: SVGProps<SVGSVGElement>) {
  return (
    <svg xmlns="http://www.w3.org/2000/svg" width="1em" height="1em" viewBox="0 0 1000 1000" aria-hidden="true" {...props}>
      ${svgToJsx(inner)}
    </svg>
  );
}
`;
}

/** Vue 3 single-file component. Attributes keep their SVG spelling; $attrs (class, style, size) go on the <svg>. */
function vueComponent(id: IconId, icon: IconData, style: IconStyle): string {
  const name = componentName(id);
  const svg = buildIconSvg(icon, { ...style, size: 24 }, { uniqueIds: true });
  const inner = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  return `<script setup lang="ts">
// ${id} - generated by DesignHub. Size with font-size or width/height; color inherits currentColor.
defineOptions({ name: "${name}", inheritAttrs: false });
</script>

<template>
  <svg xmlns="http://www.w3.org/2000/svg" width="1em" height="1em" viewBox="0 0 1000 1000" aria-hidden="true" v-bind="$attrs">
    ${inner}
  </svg>
</template>
`;
}

/**
 * Svelte 5 component. Extra props (class, style, width) are spread onto the <svg> with {...rest}.
 * Braces start an expression in Svelte markup, so any in the icon body are written as entities.
 */
function svelteComponent(id: IconId, icon: IconData, style: IconStyle): string {
  const svg = buildIconSvg(icon, { ...style, size: 24 }, { uniqueIds: true });
  const inner = svg
    .replace(/^<svg[^>]*>/, "")
    .replace(/<\/svg>$/, "")
    .replace(/[{}]/g, (brace) => (brace === "{" ? "&#123;" : "&#125;"));
  return `<script lang="ts">
  // ${id} - generated by DesignHub. Size with font-size or width/height; color inherits currentColor.
  import type { SVGAttributes } from "svelte/elements";

  let { ...rest }: SVGAttributes<SVGSVGElement> = $props();
</script>

<svg xmlns="http://www.w3.org/2000/svg" width="1em" height="1em" viewBox="0 0 1000 1000" aria-hidden="true" {...rest}>
  ${inner}
</svg>
`;
}

/**
 * The icon body for JSX that sets attributes as written (Solid, Qwik): SVG spellings stay, xlink:href
 * becomes the SVG 2 href, and braces, which open an expression in JSX, are written as entities.
 */
function verbatimJsxBody(icon: IconData, style: IconStyle): string {
  const svg = buildIconSvg(icon, { ...style, size: 24 }, { uniqueIds: true });
  return svg
    .replace(/^<svg[^>]*>/, "")
    .replace(/<\/svg>$/, "")
    .replace(/\sxlink:href=/g, " href=")
    .replace(/[{}]/g, (brace) => (brace === "{" ? "&#123;" : "&#125;"));
}

/**
 * SolidJS component. Solid sets SVG attributes as written, so the body keeps class and stroke-width
 * spellings, and props (class, style, width) are spread onto the <svg>. xlink:href becomes the SVG 2
 * href, which Solid's JSX types know. Braces open an expression in JSX, so any in the icon body (for
 * example CSS in a <style>) are written as entities.
 */
function solidComponent(id: IconId, icon: IconData, style: IconStyle): string {
  const name = componentName(id);
  const inner = verbatimJsxBody(icon, style);
  return `import type { JSX } from "solid-js";

// ${id} - generated by DesignHub. Size with font-size or width/height; color inherits currentColor.
export function ${name}(props: JSX.SvgSVGAttributes<SVGSVGElement>) {
  return (
    <svg xmlns="http://www.w3.org/2000/svg" width="1em" height="1em" viewBox="0 0 1000 1000" aria-hidden="true" {...props}>
      ${inner}
    </svg>
  );
}
`;
}

/**
 * Qwik component made with component$. Like Solid, Qwik sets SVG attributes as written, so the body
 * keeps class and stroke-width, and props (class, style, width) are spread onto the <svg>.
 */
function qwikComponent(id: IconId, icon: IconData, style: IconStyle): string {
  const name = componentName(id);
  const inner = verbatimJsxBody(icon, style);
  return `import { component$, type PropsOf } from "@builder.io/qwik";

// ${id} - generated by DesignHub. Size with font-size or width/height; color inherits currentColor.
export const ${name} = component$((props: PropsOf<"svg">) => {
  return (
    <svg xmlns="http://www.w3.org/2000/svg" width="1em" height="1em" viewBox="0 0 1000 1000" aria-hidden="true" {...props}>
      ${inner}
    </svg>
  );
});
`;
}

/**
 * Angular standalone component with `size` and `color` inputs bound on the <svg>.
 * The body keeps currentColor so the color input recolors it. It sits in an ngNonBindable group so
 * "{{" is never interpolated, and braces and @ outside <style> (raw text Angular leaves alone) are
 * written as entities so they don't open control flow blocks. Backticks, backslashes and $ are
 * escaped because the template sits in a TypeScript template literal.
 */
function angularComponent(id: IconId, icon: IconData, style: IconStyle): string {
  const name = componentName(id);
  const svg = buildIconSvg(icon, { ...style, size: 24, color: "currentColor" }, { uniqueIds: true });
  const inner = svg
    .replace(/^<svg[^>]*>/, "")
    .replace(/<\/svg>$/, "")
    .split(/(<style[^>]*>[\s\S]*?<\/style>)/)
    .map((part, index) => (index % 2 === 1 ? part : escapeAngularText(part)))
    .join("");
  return `import { Component, Input } from "@angular/core";

// ${id} - generated by DesignHub. Set size and color, or size with font-size and inherit the text color.
@Component({
  selector: "${kebabCase(name)}",
  standalone: true,
  template: \`
    <svg xmlns="http://www.w3.org/2000/svg" [attr.width]="size" [attr.height]="size" viewBox="0 0 1000 1000" aria-hidden="true" [style.color]="color">
      <g ngNonBindable>${escapeTemplateLiteral(inner)}</g>
    </svg>
  \`,
})
export class ${name}Component {
  @Input() size: string | number = "1em";
  @Input() color = ${JSON.stringify(style.color)};
}
`;
}

/**
 * Lit web component with `size` and `color` properties. The <svg> is an `html` template and the
 * icon body an `svg` template inside it, so Lit parses the artwork in the SVG namespace. The body
 * keeps currentColor, which the color property sets on the element. Reactive properties are
 * declared with `static properties` (no decorators needed), and backslashes, backticks and $ are
 * escaped because the artwork sits in a template literal.
 */
function litComponent(id: IconId, icon: IconData, style: IconStyle): string {
  const name = componentName(id);
  const tag = kebabCase(name);
  const svg = buildIconSvg(icon, { ...style, size: 24, color: "currentColor" }, { uniqueIds: true });
  const inner = escapeTemplateLiteral(svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, ""));
  return `import { LitElement, html, svg } from "lit";

// ${id} - generated by DesignHub. Set size and color, or size with font-size and inherit the text color.
export class ${name} extends LitElement {
  static properties = {
    size: { type: String },
    color: { type: String },
  };

  declare size: string;
  declare color: string;

  constructor() {
    super();
    this.size = "1em";
    this.color = ${JSON.stringify(style.color)};
  }

  render() {
    return html\`<svg xmlns="http://www.w3.org/2000/svg" width=\${this.size} height=\${this.size} viewBox="0 0 1000 1000" aria-hidden="true" style="color: \${this.color}">\${svg\`${inner}\`}</svg>\`;
  }
}

customElements.define("${tag}", ${name});

declare global {
  interface HTMLElementTagNameMap {
    "${tag}": ${name};
  }
}
`;
}

/**
 * Astro component. `size` and `color` come from Astro.props, and the rest (class, style, width) is
 * spread onto the <svg>. The body keeps currentColor so the color prop recolors it. Braces open an
 * expression in Astro markup, so any in the body are written as entities, except inside <style>,
 * which gets is:inline so Astro leaves the CSS unscoped and as written.
 */
function astroComponent(id: IconId, icon: IconData, style: IconStyle): string {
  const svg = buildIconSvg(icon, { ...style, size: 24, color: "currentColor" }, { uniqueIds: true });
  const inner = svg
    .replace(/^<svg[^>]*>/, "")
    .replace(/<\/svg>$/, "")
    .split(/(<style[^>]*>[\s\S]*?<\/style>)/)
    .map((part, index) =>
      index % 2 === 1
        ? part.replace(/^<style(?![^>]*\bis:inline\b)/, "<style is:inline")
        : part.replace(/[{}]/g, (brace) => (brace === "{" ? "&#123;" : "&#125;")),
    )
    .join("");
  return `---
// ${id} - generated by DesignHub. Set size and color, or size with font-size and inherit the text color.
import type { HTMLAttributes } from "astro/types";

interface Props extends HTMLAttributes<"svg"> {
  size?: string | number;
  color?: string;
}

const { size = "1em", color = ${JSON.stringify(style.color)}, ...rest } = Astro.props;
---

<svg xmlns="http://www.w3.org/2000/svg" width={size} height={size} viewBox="0 0 1000 1000" aria-hidden="true" style={\`color: \${color}\`} {...rest}>
  ${inner}
</svg>
`;
}

/**
 * React Native component for react-native-svg, made by the SVG Playground's converter so both
 * produce the same mapping. Props (width, height, color, style) are spread onto the <Svg>, and
 * currentColor follows the color prop. Returns a comment when the icon can't be converted.
 */
function reactNativeIcon(id: IconId, icon: IconData, style: IconStyle): string {
  const parsed = parseSvg(buildIconSvg(icon, { ...style, size: 24 }, { uniqueIds: true }));
  const result = parsed.ok ? reactNativeComponent(parsed.root, componentName(id)) : null;
  if (!result?.code) return `// ${id} could not be converted.\n`;
  const notes = result.warnings.map((warning) => `// Note: ${warning}\n`).join("");
  return `// ${id} - generated by DesignHub.\n${notes}${result.code}`;
}

/** "brand-github" → "Brand github", the accessible name an HTML export gives its icon. */
function accessibleName(id: IconId): string {
  const words = splitIconId(id).name.replace(/[-_]+/g, " ").trim();
  return words.charAt(0).toUpperCase() + words.slice(1);
}

const escapeAttribute = (value: string) =>
  value.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/**
 * Inline <svg> for plain HTML. Sized with 1em like the component exports, so font-size scales it and
 * the color follows the text. The default form is an image with an accessible name from the icon
 * name (role="img" and aria-label). The decorative form is hidden from assistive technology
 * (aria-hidden="true", no role), for an icon that sits next to text that already says the same thing.
 */
function htmlIcon(id: IconId, icon: IconData, style: IconStyle, decorative: boolean): string {
  const svg = buildIconSvg(icon, { ...style, size: 24 }, { uniqueIds: true });
  const inner = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  const accessibility = decorative
    ? 'aria-hidden="true"'
    : `role="img" aria-label="${escapeAttribute(accessibleName(id))}"`;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1em" height="1em" viewBox="0 0 1000 1000" ${accessibility}>${inner}</svg>\n`;
}

function cssDataUri(icon: IconData, style: IconStyle): string {
  // currentColor has no meaning inside a background image, so use a mask for monochrome icons.
  const svg = buildIconSvg(icon, { ...style, size: 24, color: style.color === "currentColor" ? "#000" : style.color });
  const uri = svgCssUrl(svg);
  return style.color === "currentColor"
    ? `.icon {\n  display: inline-block;\n  width: 1em;\n  height: 1em;\n  background-color: currentColor;\n  mask: ${uri} no-repeat center / contain;\n}\n`
    : `.icon {\n  display: inline-block;\n  width: 1em;\n  height: 1em;\n  background: ${uri} no-repeat center / contain;\n}\n`;
}

